def _concept(store, name):
    return store.database[CONCEPTS].find_one({"canonical_name": name})["_id"]


def test_reciprocal_rank_fusion_rewards_agreement() -> None:
    fused = fuse({"lexical": ["p1", "p2", "p3"], "semantic": ["p2", "p4"], "graph": ["p2"]})
    assert fused[0][0] == "p2" and fused[0][2] == ["lexical", "semantic", "graph"]
    assert [row[0] for row in fused] == ["p2", "p1", "p4", "p3"]


def test_hybrid_search_combines_methods_and_every_quote_is_an_exact_slice(app, store) -> None:
    found = app.search_hybrid("default", "Oxygen Generation System")
    assert found["methods"] == ["lexical", "graph"]                      # no semantic index yet
    top = found["results"][0]
    assert top["content_unit_id"] == page_id("doc-a", 1) and set(top["methods"]) == {"lexical", "graph"}
    for result in found["results"]:
        text = store.content_units.find_one({"_id": result["content_unit_id"]})["text"]
        assert text[result["start"]:result["end"]] == result["quote"]
    assert [c["name"] for c in found["concepts"]] == ["Oxygen Generation System"]


def test_semantic_retrieval_finds_meaning_without_shared_words_and_rebuilds_incrementally(app, store) -> None:
    question = "Which system makes air fit to inhale"
    assert all(r["content_unit_id"] != page_id("doc-b", 2) for r in app.search_hybrid("default", question)["results"])
    app._embedder = KeywordEmbedder()
    built = app.build_semantic_index("default")
    assert built["embedded"] == built["passages"] >= 4 and built["reused"] == 0
    found = app.search_hybrid("default", question)
    assert found["methods"] == ["lexical", "semantic", "graph"]
    hit = next(r for r in found["results"] if r["content_unit_id"] == page_id("doc-b", 2))
    assert "semantic" in hit["methods"] and hit["quote"].startswith("Atmosphere revitalization")
    assert app.build_semantic_index("default")["embedded"] == 0                 # nothing changed
    store.content_units.update_one({"_id": page_id("doc-a", 2)}, {"$set": {"text": "Zeolite beds adsorb carbon dioxide."}})
    again = app.build_semantic_index("default")
    assert again["embedded"] == 1 and again["removed"] == 1


def test_research_separates_facts_interpretations_conflicts_and_converts_units(app) -> None:
    answer = app.research("default", "How much oxygen does each crew member consume in g/day?")
    assert not answer["abstained"] and answer["passages"]
    unconfirmed = {c["statement"] for c in answer["claims"]["unconfirmed"]}     # contested: never a fact
    assert "Each crew member consumes 0.84 kg/day of oxygen." in unconfirmed and not answer["claims"]["facts"]
    assert all(c["citation_valid"] for group in answer["claims"].values() for c in group)
    assert {c["statement"] for c in answer["conflicts"]} >= {"Each crew member consumes 0.84 kg/day of oxygen.",
                                                             "Each crew member consumes 1.2 kg/day of oxygen."}
    assert sorted(c["value"] for c in answer["calculations"]) == [840.0, 1200.0]
    assert {c["unit"] for c in answer["calculations"]} == {"g/day"}

    hedged = app.research("default", "Does the electrolysis cell degrade?")
    assert [c["statement"] for c in hedged["claims"]["interpretations"]] == [
        "The electrolysis cell may degrade after two years."]               # "suggest", "may": not a fact
    assert app.research("default", "Who won the football world cup in 1998?")["abstained"]


def test_graph_exploration_paths_and_governed_visibility(app, store) -> None:
    ogs, water = _concept(store, "Oxygen Generation System"), _concept(store, "Water")
    near = app.explore("default", [ogs], hops=1)
    assert {n["name"] for n in near["nodes"]} == {"Oxygen Generation System", "Electrolysis"}
    far = app.explore("default", [ogs], hops=2)
    assert {n["name"]: n["distance"] for n in far["nodes"]}["Water"] == 2 and len(far["edges"]) == 2
    steps = app.connection("default", ogs, water)["path"]
    assert [s["relationship"]["type"] for s in steps] == ["uses", "uses"]
    assert steps[0]["relationship"]["evidence"][0]["quote"].startswith("The Oxygen Generation System")
    detail = app.concept_knowledge("default", _concept(store, "Electrolysis"))
    assert detail["claims"]["interpretations"] and detail["documents"] == ["doc-a", "doc-b"]

    app.adjudicate("default", water, "ana", "reject", "too generic")
    assert water not in app.knowledge_graph("default").concepts               # a rejected item is never served
    assert app.connection("default", ogs, water)["path"] is None
    with pytest.raises(NotFound):
        app.explore("default", [water])


