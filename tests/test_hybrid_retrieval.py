class FakeText:
    model = "fake-qwen"

    def complete(self, system, messages, schema):
        passage = messages[0]["content"]
        table = CLAIMS_BY_MARKER if "claims" in schema["properties"] else CONCEPTS_BY_MARKER
        empty = [] if "claims" in schema["properties"] else {"concepts": [], "relationships": []}
        answer = next((a for marker, a in table.items() if marker in passage), empty)
        return LLMResponse(json.dumps({"claims": answer} if "claims" in schema["properties"] else answer),
                           "end_turn", self.model)


class KeywordEmbedder:
    """Bag of meaning-words: different words with the same meaning share a dimension."""
    model_name = "keyword-test"
    MEANING = {"inhale": "air", "breathable": "air", "breathe": "air", "atmosphere": "air", "air": "air", "oxygen": "oxygen",
               "zeolite": "co2", "carbon": "co2", "dioxide": "co2", "water": "water", "electrolysis": "water"}
    DIMS = sorted(set(MEANING.values()))

    def __init__(self) -> None:
        self.calls = 0

    def embed(self, texts):
        self.calls += len(texts)
        vectors = np.zeros((len(texts), len(self.DIMS) + 1), dtype="float32")
        for row, text in enumerate(texts):
            for word in re.findall(r"[a-z]+", text.lower()):
                if word in self.MEANING:
                    vectors[row, self.DIMS.index(self.MEANING[word])] += 1
            vectors[row, -1] = 0.01
        return vectors


